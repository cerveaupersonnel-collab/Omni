#!/usr/bin/env bash
# Writes lib/firebase_options.dart and android/app/google-services.json from Codemagic secrets.
# If a secret is missing, writes a build-only stub so the compile succeeds. A stub build
# CANNOT talk to Firebase and must never be uploaded to Google Play.
set -euo pipefail
cd "$(dirname "$0")/.."

if [ -n "${FIREBASE_OPTIONS_DART_B64:-}" ]; then
  echo "$FIREBASE_OPTIONS_DART_B64" | base64 --decode > lib/firebase_options.dart
else
  echo "WARNING: FIREBASE_OPTIONS_DART_B64 missing: using a build-only stub."
  cat > lib/firebase_options.dart <<'DART'
// CI build-only stub. NOT for release: replace with the file generated by `flutterfire configure`.
import 'package:firebase_core/firebase_core.dart';

class DefaultFirebaseOptions {
  static const FirebaseOptions currentPlatform = FirebaseOptions(
    apiKey: 'ci-build-only',
    appId: '1:000000000000:android:0000000000000000',
    messagingSenderId: '000000000000',
    projectId: 'omni-ci-build-only',
  );
}
DART
fi

mkdir -p android/app
if [ -n "${GOOGLE_SERVICES_JSON_B64:-}" ]; then
  echo "$GOOGLE_SERVICES_JSON_B64" | base64 --decode > android/app/google-services.json
else
  echo "WARNING: GOOGLE_SERVICES_JSON_B64 missing: using a build-only stub."
  cat > android/app/google-services.json <<'JSON'
{
  "project_info": {"project_number": "000000000000", "project_id": "omni-ci-build-only", "storage_bucket": "omni-ci-build-only.appspot.com"},
  "client": [{
    "client_info": {"mobilesdk_app_id": "1:000000000000:android:0000000000000000", "android_client_info": {"package_name": "com.omni.omni"}},
    "oauth_client": [],
    "api_key": [{"current_key": "ci-build-only"}],
    "services": {"appinvite_service": {"other_platform_oauth_client": []}}
  }],
  "configuration_version": "1"
}
JSON
fi
