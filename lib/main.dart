import 'package:firebase_app_check/firebase_app_check.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'app.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  // Every callable enforces App Check. Release builds use Play Integrity;
  // debug builds use the debug provider (register the token printed in logcat).
  await FirebaseAppCheck.instance.activate(
    providerAndroid: kDebugMode ? AndroidProvider.debug : AndroidProvider.playIntegrity,
  );
  runApp(const ProviderScope(child: OmniApp()));
}
